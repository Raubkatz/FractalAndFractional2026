class MemoryFRMSprop(_MemoryFractionalBase, _KerasOptimizerBase):
    """
    Explicit memory-based fractional RMSprop (corrected).

    The fractional gradient drives the update direction; the squared-
    gradient accumulator uses the raw gradient by default.
    """

    def __init__(
        self,
        learning_rate: float = 0.001,
        lr: float = None,
        rho: float = 0.9,
        momentum: float = 0.0,
        epsilon: float = 1e-7,
        centered: bool = False,
        vderiv: float = 1.0,
        history_size: int = 8,
        normalize_coefficients: bool = False,
        coeff_epsilon: float = 1e-12,
        norm_match: bool = True,
        use_raw_gradient_for_second_moment: bool = True,
        descent_check: bool = True,
        name: str = "MemoryFRMSprop",
        **kwargs: Any,
    ):
        super(MemoryFRMSprop, self).__init__(name, **kwargs)

        actual_lr = learning_rate if lr is None else lr
        self._set_hyper("learning_rate", actual_lr)

        if not (0.0 <= rho < 1.0):
            raise ValueError("`rho` must satisfy 0 <= rho < 1.")
        if not (0.0 <= momentum < 1.0):
            raise ValueError("`momentum` must satisfy 0 <= momentum < 1.")
        if epsilon <= 0.0:
            raise ValueError("`epsilon` must be > 0.")

        self.rho = float(rho)
        self.momentum = float(momentum)
        self.epsilon = float(epsilon)
        self.centered = bool(centered)

        self._init_memory_fractional_args(
            vderiv=vderiv,
            history_size=history_size,
            normalize_coefficients=normalize_coefficients,
            coeff_epsilon=coeff_epsilon,
            norm_match=norm_match,
            use_raw_gradient_for_second_moment=use_raw_gradient_for_second_moment,
            descent_check=descent_check,
        )

    def _create_slots(self, var_list):
        for var in var_list:
            self._create_history_slot(var)
            self.add_slot(var, "velocity")
            if self.momentum > 0.0:
                self.add_slot(var, "momentum")
            if self.centered:
                self.add_slot(var, "avg_grad")

    def _resource_apply_dense(self, grad, var, apply_state=None):
        dtype = var.dtype.base_dtype
        lr_t = tf.cast(self._decayed_lr(dtype), dtype)
        rho_t = tf.cast(self.rho, dtype)
        eps_t = tf.cast(self.epsilon, dtype)

        _, frac_grad, second_grad, hist_op = (
            self._direction_and_second_moment_grads(grad, var)
        )

        velocity = self.get_slot(var, "velocity")
        new_velocity = rho_t * velocity + (1.0 - rho_t) * tf.square(second_grad)
        velocity_op = velocity.assign(new_velocity, use_locking=self._use_locking)

        if self.centered:
            avg_grad = self.get_slot(var, "avg_grad")
            new_avg = rho_t * avg_grad + (1.0 - rho_t) * second_grad
            avg_op = avg_grad.assign(new_avg, use_locking=self._use_locking)
            denom = tf.sqrt(new_velocity - tf.square(new_avg) + eps_t)
        else:
            avg_op = tf.no_op()
            denom = tf.sqrt(new_velocity + eps_t)

        if self.momentum > 0.0:
            mu = tf.cast(self.momentum, dtype)
            mom = self.get_slot(var, "momentum")
            new_mom = mu * mom + lr_t * frac_grad / denom
            mom_op = mom.assign(new_mom, use_locking=self._use_locking)
            var_op = var.assign_sub(new_mom, use_locking=self._use_locking)
            return tf.group(var_op, hist_op, velocity_op, avg_op, mom_op)

        var_op = var.assign_sub(
            lr_t * frac_grad / denom, use_locking=self._use_locking
        )
        return tf.group(var_op, hist_op, velocity_op, avg_op)

    def _resource_apply_sparse(self, grad, var, indices, apply_state=None):
        sparse = tf.IndexedSlices(
            values=grad, indices=indices, dense_shape=tf.shape(var)
        )
        return self._resource_apply_dense(sparse, var, apply_state=apply_state)

    def get_config(self):
        config = super(MemoryFRMSprop, self).get_config()
        config.update(
            {
                "learning_rate": self._serialize_hyperparameter("learning_rate"),
                "rho": self.rho,
                "momentum": self.momentum,
                "epsilon": self.epsilon,
                "centered": self.centered,
                **self._memory_fractional_config(),
            }
        )
        return config


