class MemoryFAdadelta(_MemoryFractionalBase, _KerasOptimizerBase):
    """
    Explicit memory-based fractional Adadelta (corrected).

    Direction from the fractional gradient; both accumulators from the raw
    gradient / raw-driven update by default.
    """

    def __init__(
        self,
        learning_rate: float = 1.0,
        lr: float = None,
        rho: float = 0.95,
        epsilon: float = 1e-7,
        vderiv: float = 1.0,
        history_size: int = 8,
        normalize_coefficients: bool = False,
        coeff_epsilon: float = 1e-12,
        norm_match: bool = True,
        use_raw_gradient_for_second_moment: bool = True,
        descent_check: bool = True,
        name: str = "MemoryFAdadelta",
        **kwargs: Any,
    ):
        super(MemoryFAdadelta, self).__init__(name, **kwargs)

        actual_lr = learning_rate if lr is None else lr
        self._set_hyper("learning_rate", actual_lr)

        if not (0.0 <= rho < 1.0):
            raise ValueError("`rho` must satisfy 0 <= rho < 1.")
        if epsilon <= 0.0:
            raise ValueError("`epsilon` must be > 0.")

        self.rho = float(rho)
        self.epsilon = float(epsilon)

        self._init_memory_fractional_args(
            vderiv=vderiv,
            history_size=history_size,
            normalize_coefficients=normalize_coefficients,
            coeff_epsilon=coeff_epsilon,
            norm_match=norm_match,
            use_raw_gradient_for_second_moment=use_raw_gradient_for_second_moment,
            descent_check=descent_check,
        )

    def _create_slots(self, var_list):
        for var in var_list:
            self._create_history_slot(var)
            self.add_slot(var, "accumulated_grad")
            self.add_slot(var, "accumulated_delta")

    def _resource_apply_dense(self, grad, var, apply_state=None):
        dtype = var.dtype.base_dtype
        lr_t = tf.cast(self._decayed_lr(dtype), dtype)
        rho_t = tf.cast(self.rho, dtype)
        eps_t = tf.cast(self.epsilon, dtype)

        _, frac_grad, second_grad, hist_op = (
            self._direction_and_second_moment_grads(grad, var)
        )

        acc_g = self.get_slot(var, "accumulated_grad")
        acc_d = self.get_slot(var, "accumulated_delta")

        new_acc_g = rho_t * acc_g + (1.0 - rho_t) * tf.square(second_grad)
        acc_g_op = acc_g.assign(new_acc_g, use_locking=self._use_locking)

        rms_delta = tf.sqrt(acc_d + eps_t)
        rms_grad = tf.sqrt(new_acc_g + eps_t)
        delta = -(rms_delta / rms_grad) * frac_grad

        new_acc_d = rho_t * acc_d + (1.0 - rho_t) * tf.square(delta)
        acc_d_op = acc_d.assign(new_acc_d, use_locking=self._use_locking)

        var_op = var.assign_add(lr_t * delta, use_locking=self._use_locking)
        return tf.group(var_op, hist_op, acc_g_op, acc_d_op)

    def _resource_apply_sparse(self, grad, var, indices, apply_state=None):
        sparse = tf.IndexedSlices(
            values=grad, indices=indices, dense_shape=tf.shape(var)
        )
        return self._resource_apply_dense(sparse, var, apply_state=apply_state)

    def get_config(self):
        config = super(MemoryFAdadelta, self).get_config()
        config.update(
            {
                "learning_rate": self._serialize_hyperparameter("learning_rate"),
                "rho": self.rho,
                "epsilon": self.epsilon,
                **self._memory_fractional_config(),
            }
        )
        return config


