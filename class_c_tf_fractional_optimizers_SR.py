class MemoryFAdam(_MemoryFractionalBase, _KerasOptimizerBase):
    """
    Explicit memory-based fractional Adam (corrected).

    First moment from the fractional gradient; second moment from the raw
    gradient by default (set use_raw_gradient_for_second_moment=False to
    reproduce the original both-moments behaviour).
    """

    def __init__(
        self,
        learning_rate: float = 0.001,
        lr: float = None,
        beta_1: float = 0.9,
        beta_2: float = 0.999,
        epsilon: float = 1e-7,
        amsgrad: bool = False,
        vderiv: float = 1.0,
        history_size: int = 8,
        normalize_coefficients: bool = False,
        coeff_epsilon: float = 1e-12,
        norm_match: bool = True,
        use_raw_gradient_for_second_moment: bool = True,
        descent_check: bool = True,
        name: str = "MemoryFAdam",
        **kwargs: Any,
    ):
        super(MemoryFAdam, self).__init__(name, **kwargs)

        actual_lr = learning_rate if lr is None else lr
        self._set_hyper("learning_rate", actual_lr)

        if not (0.0 <= beta_1 < 1.0):
            raise ValueError("`beta_1` must satisfy 0 <= beta_1 < 1.")
        if not (0.0 <= beta_2 < 1.0):
            raise ValueError("`beta_2` must satisfy 0 <= beta_2 < 1.")
        if epsilon <= 0.0:
            raise ValueError("`epsilon` must be > 0.")

        self.beta_1 = float(beta_1)
        self.beta_2 = float(beta_2)
        self.epsilon = float(epsilon)
        self.amsgrad = bool(amsgrad)

        self._init_memory_fractional_args(
            vderiv=vderiv,
            history_size=history_size,
            normalize_coefficients=normalize_coefficients,
            coeff_epsilon=coeff_epsilon,
            norm_match=norm_match,
            use_raw_gradient_for_second_moment=use_raw_gradient_for_second_moment,
            descent_check=descent_check,
        )

    def _create_slots(self, var_list):
        for var in var_list:
            self._create_history_slot(var)
            self.add_slot(var, "m")
            self.add_slot(var, "v")
            if self.amsgrad:
                self.add_slot(var, "vhat")

    def _resource_apply_dense(self, grad, var, apply_state=None):
        dtype = var.dtype.base_dtype
        lr_t = tf.cast(self._decayed_lr(dtype), dtype)
        b1 = tf.cast(self.beta_1, dtype)
        b2 = tf.cast(self.beta_2, dtype)
        eps_t = tf.cast(self.epsilon, dtype)
        step = tf.cast(self.iterations + 1, dtype)

        _, frac_grad, second_grad, hist_op = (
            self._direction_and_second_moment_grads(grad, var)
        )

        m = self.get_slot(var, "m")
        v = self.get_slot(var, "v")

        new_m = b1 * m + (1.0 - b1) * frac_grad
        new_v = b2 * v + (1.0 - b2) * tf.square(second_grad)

        m_op = m.assign(new_m, use_locking=self._use_locking)
        v_op = v.assign(new_v, use_locking=self._use_locking)

        # Keras-exact formulation: bias correction is folded into the
        # learning rate and epsilon sits outside the *uncorrected* sqrt.
        # This makes the nu=1 fallback bit-compatible with the Keras Adam
        # baseline used in the experiments.
        b1_pow = tf.pow(b1, step)
        b2_pow = tf.pow(b2, step)
        lr_corr = lr_t * tf.sqrt(1.0 - b2_pow) / (1.0 - b1_pow)

        if self.amsgrad:
            vhat = self.get_slot(var, "vhat")
            new_vhat = tf.maximum(vhat, new_v)
            vhat_op = vhat.assign(new_vhat, use_locking=self._use_locking)
            denom_v = new_vhat
        else:
            vhat_op = tf.no_op()
            denom_v = new_v

        var_op = var.assign_sub(
            lr_corr * new_m / (tf.sqrt(denom_v) + eps_t),
            use_locking=self._use_locking,
        )
        return tf.group(var_op, hist_op, m_op, v_op, vhat_op)

    def _resource_apply_sparse(self, grad, var, indices, apply_state=None):
        sparse = tf.IndexedSlices(
            values=grad, indices=indices, dense_shape=tf.shape(var)
        )
        return self._resource_apply_dense(sparse, var, apply_state=apply_state)

    def get_config(self):
        config = super(MemoryFAdam, self).get_config()
        config.update(
            {
                "learning_rate": self._serialize_hyperparameter("learning_rate"),
                "beta_1": self.beta_1,
                "beta_2": self.beta_2,
                "epsilon": self.epsilon,
                "amsgrad": self.amsgrad,
                **self._memory_fractional_config(),
            }
        )
        return config


